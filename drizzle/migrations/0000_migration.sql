CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role text DEFAULT 'student',
  full_name text, learner_path text, education_level text, grade_level text,
  school_name text, county text, target_exam_year integer,
  onboarding_completed boolean DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.profiles TO authenticated; GRANT ALL ON public.profiles TO service_role;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_profile_read ON public.profiles FOR SELECT TO authenticated USING (id = auth.uid());
CREATE POLICY own_profile_update ON public.profiles FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());

CREATE FUNCTION public.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
  INSERT INTO public.profiles(id, role, full_name, learner_path, education_level, grade_level, school_name, target_exam_year)
  VALUES (NEW.id, 'student', NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'learner_path',
    NEW.raw_user_meta_data->>'education_level', NEW.raw_user_meta_data->>'grade_level', NEW.raw_user_meta_data->>'school_name',
    CASE WHEN (NEW.raw_user_meta_data->>'target_exam_year') ~ '^\d{4}$' THEN (NEW.raw_user_meta_data->>'target_exam_year')::integer END)
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

