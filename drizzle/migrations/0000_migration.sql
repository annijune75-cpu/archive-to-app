CREATE FUNCTION public.submit_exam_attempt(p_answers jsonb) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE total int; correct int; subj bigint; rev jsonb;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Sign in to continue.'; END IF;
  IF jsonb_typeof(p_answers) <> 'array' OR jsonb_array_length(p_answers) < 1 OR jsonb_array_length(p_answers) > 200 THEN RAISE EXCEPTION 'Invalid answers'; END IF;
  WITH given AS (SELECT DISTINCT ON (x->>'question_id') (x->>'question_id')::uuid AS qid, x->>'selected_option' AS opt FROM jsonb_array_elements(p_answers) x),
  graded AS (SELECT q.id, q.subject_id, q.explanation, a.correct_option, (a.correct_option = g.opt) AS ok
    FROM given g JOIN public.exam_questions q ON q.id = g.qid AND q.is_published JOIN public.exam_question_answers a ON a.question_id = q.id)
  SELECT count(*), count(*) FILTER (WHERE ok), min(subject_id),
    coalesce(jsonb_agg(jsonb_build_object('question_id', id, 'is_correct', ok, 'correct_option', correct_option, 'explanation', explanation)), '[]'::jsonb)
  INTO total, correct, subj, rev FROM graded;
  IF total = 0 THEN RAISE EXCEPTION 'No published questions were answered.'; END IF;
  INSERT INTO public.exam_attempts(user_id, subject_id, score, total_questions, answers) VALUES (auth.uid(), subj, correct, total, p_answers);
  RETURN jsonb_build_object('score', correct, 'total_questions', total, 'review', rev);
END $$;
REVOKE ALL ON FUNCTION public.submit_exam_attempt(jsonb) FROM PUBLIC, anon; GRANT EXECUTE ON FUNCTION public.submit_exam_attempt(jsonb) TO authenticated;

